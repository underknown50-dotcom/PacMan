#!/usr/bin/env bash
# Build and archive the self-contained Linux release from any working directory.
set -euo pipefail

project_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
python="$project_root/.venv/bin/python"
if [[ ! -x "$python" && -x "$project_root/../.venv/bin/python" ]]; then
    python="$project_root/../.venv/bin/python"
fi
release_dir="$project_root/dist/Pacman42-Linux"
archive_path="$project_root/release/Pacman42-Linux-x86_64.tar.gz"

if [[ "$(uname -s)" != "Linux" || "$(uname -m)" != "x86_64" ]]; then
    printf '%s\n' 'Build this release on an x86_64 Linux machine.' >&2
    exit 1
fi
if [[ ! -x "$python" ]]; then
    printf '%s\n' 'Development environment missing. Run make install first.' >&2
    exit 1
fi
for required in pac-man.py pacman.spec config.json PLAYER_GUIDE.txt README.md; do
    if [[ ! -f "$project_root/$required" ]]; then
        printf 'Required release input is missing: %s\n' "$required" >&2
        exit 1
    fi
done

cd -- "$project_root"
"$python" tools/verify_integrity.py
mkdir -p -- build/pyinstaller-cache release
export XDG_CACHE_HOME="$project_root/build/pyinstaller-cache"
"$python" -m PyInstaller --noconfirm --clean pacman.spec

# This directory is generated by this script; user data lives outside it.
rm -rf -- "$release_dir"
mkdir -p -- "$release_dir"
cp -a -- "$project_root/dist/pacman42/." "$release_dir/"
cp -- config.json config.comments.json PLAYER_GUIDE.txt README.md "$release_dir/"
cp -- PACMAN_TEAM_PARTS.md "$release_dir/"
cat > "$release_dir/run.sh" <<'LAUNCHER'
#!/usr/bin/env sh
set -eu
launcher_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd -- "$launcher_dir"
if [ "$#" -eq 0 ]; then
    set -- config.json
fi
exec ./pacman42 "$@"
LAUNCHER
chmod +x -- "$release_dir/run.sh"
tar -C "$project_root/dist" -czf "$archive_path" Pacman42-Linux
printf 'Release folder: %s\nArchive: %s\n' "$release_dir" "$archive_path"
